// Generates docs/rules.md from the rule definitions so the reference cannot drift.
// Run: npm run docs   (CI fails if the committed file is out of date)
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { PLATFORM_LABELS } from '../src/platforms.js';
import { RULES } from '../src/rules/index.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const target = join(root, 'docs', 'rules.md');

/** @param {string} s */
const cell = (s) => s.replace(/\|/g, '\\|').replace(/\n/g, ' ');

export function renderRulesDoc() {
  const lines = [
    '# Rules',
    '',
    '<!-- Generated by `npm run docs`. Do not edit by hand. -->',
    '',
    `portsh ships ${RULES.length} rules. Every rule carries a runnable proof; \`portsh verify\` executes them on your machine.`,
    'Use `portsh explain <rule-id>` for details, and silence a finding with `# portsh-ignore <rule-id>`.',
    '',
    '| Rule | Breaks on | What | Severity |',
    '| --- | --- | --- | --- |',
  ];
  for (const r of RULES) {
    lines.push(`| [\`${r.id}\`](#${r.id}) | ${r.fails.map((p) => PLATFORM_LABELS[p]).join(', ')} | ${cell(r.title)} | ${r.severity} |`);
  }
  for (const r of RULES) {
    const probe = r.probes.find((p) => p.bad);
    lines.push(
      '',
      `## ${r.id}`,
      '',
      `**${r.title}** · breaks on ${r.fails.map((p) => PLATFORM_LABELS[p]).join(', ')} · ${r.severity}`,
      '',
      r.why,
      '',
      `**Fix:** ${r.fix}`,
    );
    if (probe?.bad) {
      lines.push('', '```sh', '# breaks', probe.bad);
      if (probe.good) lines.push('', '# portable', probe.good);
      lines.push('```');
    }
  }
  return `${lines.join('\n')}\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const next = renderRulesDoc();
  if (process.argv.includes('--check')) {
    let current = '';
    try {
      current = readFileSync(target, 'utf8');
    } catch {
      /* missing file counts as out of date */
    }
    if (current !== next) {
      console.error('docs/rules.md is out of date. Run: npm run docs');
      process.exit(1);
    }
  } else {
    writeFileSync(target, next);
    console.log(`wrote ${target}`);
  }
}
